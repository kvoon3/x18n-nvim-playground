import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { buildAssets } from './build-assets.mjs';
import { checkoutPlugin } from './checkout-plugin.mjs';

const run = promisify(execFile);
const siteRoot = fileURLToPath(new URL('..', import.meta.url));
const pluginRoot = process.env.X18N_NVIM
  ? resolve(process.env.X18N_NVIM)
  : await checkoutPlugin();
const assetRoot = process.env.DEMO_ASSETS
  ? resolve(process.env.DEMO_ASSETS)
  : join(siteRoot, 'build/assets');
if (!process.env.DEMO_ASSETS) {
  await buildAssets({ demoRoot: siteRoot, repoRoot: pluginRoot, workDir: join(siteRoot, 'build') });
}
const publicDir = join(siteRoot, 'public');
const stage = join(siteRoot, 'build/site');

// .bin URLs keep static servers from adding Content-Encoding: gzip to the tarballs.
const ASSETS = [
  { source: 'nodejs-apk.tar.gz', guest: 'nodejs-apk.tar.gz', url: 'nodejs-apk.bin' },
  { source: 'apk-repo-rest.tar.gz', guest: 'apk-repo-rest.tar.gz', url: 'apk-repo-rest.bin' },
  { source: 'x18n-lsp-riscv64-musl.tar.gz', guest: 'x18n-lsp.tar.gz', url: 'x18n-lsp.bin' },
];

const hash = async (path) => createHash('sha256').update(await readFile(path)).digest('hex');
const size = async (path) => (await stat(path)).size;

await rm(publicDir, { recursive: true, force: true });
await mkdir(publicDir, { recursive: true });
const install = [];
for (const asset of ASSETS) {
  const source = join(assetRoot, asset.source);
  await cp(source, join(publicDir, asset.url));
  install.push({
    url: `/${asset.url}`,
    path: `demos/x18n/${asset.guest}`,
    sha256: await hash(source),
    size: await size(source),
  });
}

await rm(stage, { recursive: true, force: true });
await mkdir(join(stage, 'x18n.nvim'), { recursive: true });
await mkdir(join(stage, 'config/nvim'), { recursive: true });
await cp(join(pluginRoot, 'lua'), join(stage, 'x18n.nvim/lua'), { recursive: true });
await cp(join(pluginRoot, 'plugin'), join(stage, 'x18n.nvim/plugin'), { recursive: true });
await cp(join(pluginRoot, 'playground'), join(stage, 'playground'), {
  recursive: true,
  filter: (source) =>
    !/(^|\/)(node_modules|\.git|\.cache)(\/|$)/.test(source) &&
    !/(^|\/)\._/.test(source) &&
    !/(^|\/)\.DS_Store$/.test(source),
});
await cp(join(siteRoot, 'guest/init.lua'), join(stage, 'config/nvim/init.lua'));

const runSh = `#!/bin/sh
set -e
cd "$(dirname "$0")"
printf '%s  nodejs-apk.tar.gz\\n%s  apk-repo-rest.tar.gz\\n%s  x18n-lsp.tar.gz\\n' ${install[0].sha256} ${install[1].sha256} ${install[2].sha256} | sha256sum -c -
mkdir -p /opt/apk-repo/riscv64
tar -xzf nodejs-apk.tar.gz -C /opt/apk-repo/riscv64
tar -xzf apk-repo-rest.tar.gz -C /opt/apk-repo/riscv64
apk index --rewrite-arch riscv64 -o /opt/apk-repo/riscv64/APKINDEX.tar.gz /opt/apk-repo/riscv64/*.apk
echo /opt/apk-repo > /etc/apk/repositories
apk add --allow-untrusted --no-network neovim nodejs
mkdir -p /opt/x18n
tar -xzf x18n-lsp.tar.gz -C /opt/x18n
ln -sf /opt/x18n/node_modules/@x18n/lsp/bin.mjs /usr/local/bin/x18n-lsp
chmod +x /opt/x18n/node_modules/@x18n/lsp/bin.mjs
echo __X18N_NVIM__
XDG_CONFIG_HOME="$PWD/config" nvim
`;
await writeFile(join(stage, 'run.sh'), runSh, { mode: 0o755 });

await run('tar', ['-czf', join(publicDir, 'site.bin'), '-C', stage, '.'], {
  env: { ...process.env, COPYFILE_DISABLE: '1' },
});
const site = {
  url: '/site.bin',
  path: 'demos/x18n/site.tar.gz',
  sha256: await hash(join(publicDir, 'site.bin')),
  size: await size(join(publicDir, 'site.bin')),
};

await mkdir(join(siteRoot, 'src'), { recursive: true });
await writeFile(
  join(siteRoot, 'src/demo.generated.ts'),
  `// SPDX-License-Identifier: MIT
// Copyright (C) 2026 kvoon3
// Generated by scripts/assets.mjs. Do not edit.
export const SITE = ${JSON.stringify(site, null, 2)} as const;
export const INSTALL = ${JSON.stringify(install, null, 2)} as const;
`,
);

console.log(`site: ${site.size} bytes, ${install.length} install assets`);
